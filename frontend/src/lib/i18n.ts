// Client helper function to read active locale from browser URL search query parameters
export function getLocaleFromUrl(): string {
  if (typeof window !== 'undefined') {
    const urlParams = new URLSearchParams(window.location.search);
    return urlParams.get('locale') ?? localStorage.getItem('locale') ?? 'en';
  }
  return 'en';
}

export function translate(key: string, localeOverride?: string): string {
  const loc = localeOverride ?? getLocaleFromUrl();
  const dict = translations[loc] ?? translations.en;
  return dict[key] ?? translations.en[key] ?? key;
}
